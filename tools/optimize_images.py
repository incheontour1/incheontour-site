"""Generate responsive WebP variants + js/img-manifest.js.
Run from repo root:  python3 tools/optimize_images.py
Originals in assets/img stay untouched (used for downloads / zoom viewers)."""
import os, glob, json
from PIL import Image, ImageOps
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
IMG = os.path.join(ROOT, 'assets', 'img')
OUT = os.path.join(IMG, 'opt')
WIDTHS = [400, 800, 1200, 1600, 2000]
SKIP = ('logo', 'favicon', 'apple-touch', 'map_page')
QUALITY = 78
os.makedirs(OUT, exist_ok=True)

def variants(src, stem, widths, outdir):
    im = ImageOps.exif_transpose(Image.open(src)).convert('RGB')
    ow, oh = im.size
    ws = sorted({w for w in widths if w < ow} | {min(ow, max(widths))})
    for w in ws:
        dst = os.path.join(outdir, f'{stem}-{w}.webp')
        if os.path.exists(dst) and os.path.getmtime(dst) >= os.path.getmtime(src):
            continue
        h = round(oh * w / ow)
        im.resize((w, h), Image.LANCZOS).save(dst, 'WEBP', quality=QUALITY, method=6)
    return [ow, oh, ws]

manifest = {}
for src in sorted(glob.glob(os.path.join(IMG, '*.jpg')) + glob.glob(os.path.join(IMG, '*.png'))):
    stem = os.path.splitext(os.path.basename(src))[0]
    if stem.startswith(SKIP):
        continue
    manifest[stem] = variants(src, stem, WIDTHS, OUT)

# guidebook pages: stage (800/1200) + thumbnails (160)
gbo = os.path.join(IMG, 'gb', 'opt'); os.makedirs(gbo, exist_ok=True)
for src in sorted(glob.glob(os.path.join(IMG, 'gb', 'p-*.jpg'))):
    stem = os.path.splitext(os.path.basename(src))[0]
    variants(src, stem, [160, 800, 1200], gbo)

js = 'window.IMGM=' + json.dumps(manifest, separators=(',', ':')) + ';\n'
open(os.path.join(ROOT, 'js', 'img-manifest.js'), 'w').write(
    '/* generated by tools/optimize_images.py — [width, height, [webp widths]] */\n' + js)
print(len(manifest), 'images ->', OUT)
